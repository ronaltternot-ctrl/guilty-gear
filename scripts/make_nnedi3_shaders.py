#!/usr/bin/env python3
"""Builds the NNEDI3 post-processing shaders (neural-network upscaling of the final image).

PPSSPP already ships NNEDI3 (nns16, 8x4 window) as a *texture* upscaler, which changes the
game's textures/sprites. This script takes the same trained network weights from PPSSPP's
tex_nnedi3_2x_single.csh and emits *post-processing* fragment shaders instead, so only the
final picture is upscaled and the sprites themselves are untouched.

The chain (see acplus.ini) is:
  1. acplus_nnedi3[_rgb]_v.fsh  game image at 1x (480x272) -> doubles the rows (runs at 960x544)
  2. acplus_nnedi3[_rgb]_h.fsh  doubles the columns                       (960x544)
  3. acplus_upscale_final.fsh   Catmull-Rom from the 2x image to the screen, fixing the
                                half-pixel shift NNEDI3 introduces.

Two variants:
  luma  - the network predicts brightness only; color comes from cubic interpolation and is
          corrected to the predicted brightness. 3x cheaper, recommended.
  rgb   - the network runs on R, G and B separately. Best quality, for powerful phones.

The output is plain GLSL ES 1.00 (texture2D, gl_FragColor) as PPSSPP's post shaders expect;
PPSSPP translates it for Vulkan / GLES 3 itself.

Usage: python3 scripts/make_nnedi3_shaders.py <ppsspp_dir> <output_dir>
"""
import os
import re
import struct
import sys

WEIGHT_RE = re.compile(r"W\((\d),(-?\d+),(-?\d+),(-?\d+),(-?\d+)\)")
WS_RE = re.compile(r"WS\((-?\d+),(-?\d+)\)")


def f32(bits):
    return struct.unpack("<f", struct.pack("<i", int(bits)))[0]


def lit(value):
    """GLSL float literal that always has a '.' or an exponent."""
    s = "%.9g" % value
    if "e" not in s and "." not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s


def extract_kernel(src, name):
    """Returns a list of 16 neurons: (sum1 weights[8][4], sum2 weights[8][4], ws0, ws1)."""
    start = src.index("float %s(vec4 samples[8]) {" % name)
    end = src.index("return clamp(mstd0", start)
    body = src[start:end]
    neurons = []
    for line in body.splitlines():
        line = line.strip()
        if not line.startswith("sum1="):
            continue
        parts = line.split(";")
        s1 = [m for m in WEIGHT_RE.findall(parts[0])]
        s2 = [m for m in WEIGHT_RE.findall(parts[1])]
        ws = WS_RE.search(parts[2])
        assert len(s1) == 8 and len(s2) == 8 and ws, line[:80]
        assert [int(m[0]) for m in s1] == list(range(8))
        assert [int(m[0]) for m in s2] == list(range(8))
        w1 = [[f32(v) for v in m[1:]] for m in s1]
        w2 = [[f32(v) for v in m[1:]] for m in s2]
        neurons.append((w1, w2, f32(ws.group(1)), f32(ws.group(2))))
    assert len(neurons) == 16, len(neurons)
    return neurons


def kernel_glsl(fname, neurons):
    """One NNEDI3 evaluation on 8 vec4 samples (32 values of one channel)."""
    out = []
    out.append("float %s(vec4 s0, vec4 s1, vec4 s2, vec4 s3, vec4 s4, vec4 s5, vec4 s6, vec4 s7) {" % fname)
    out.append("\tvec4 one = vec4(1.0);")
    out.append("\tfloat sum = dot(s0, one) + dot(s1, one) + dot(s2, one) + dot(s3, one) + dot(s4, one) + dot(s5, one) + dot(s6, one) + dot(s7, one);")
    out.append("\tfloat sumsq = dot(s0, s0) + dot(s1, s1) + dot(s2, s2) + dot(s3, s3) + dot(s4, s4) + dot(s5, s5) + dot(s6, s6) + dot(s7, s7);")
    out.append("\tfloat mstd0 = sum / 32.0;")
    out.append("\tfloat mstd1 = sumsq / 32.0 - mstd0 * mstd0;")
    out.append("\tfloat mstd2 = mstd1 >= 1.192092896e-7 ? inversesqrt(mstd1) : 0.0;")
    out.append("\tmstd1 *= mstd2;")
    out.append("\tfloat vsum = 0.0;")
    out.append("\tfloat wsum = 0.0;")
    out.append("\tfloat sum1;")
    out.append("\tfloat sum2;")
    for w1, w2, ws0, ws1 in neurons:
        def dots(weights):
            return " + ".join(
                "dot(s%d, vec4(%s))" % (i, ", ".join(lit(v) for v in weights[i])) for i in range(8))
        out.append("\tsum1 = " + dots(w1) + ";")
        out.append("\tsum2 = " + dots(w2) + ";")
        out.append("\tsum1 = exp(sum1 * mstd2 + %s);" % lit(ws0))
        out.append("\tsum2 = sum2 * mstd2 + %s;" % lit(ws1))
        out.append("\twsum += sum1;")
        out.append("\tvsum += sum1 * (sum2 / (1.0 + abs(sum2)));")
    out.append("\treturn clamp(mstd0 + 5.0 * vsum / wsum * mstd1, 0.0, 1.0);")
    out.append("}")
    return "\n".join(out)


HEADER = """// {title}
// Generated by scripts/make_nnedi3_shaders.py. Do not edit by hand.
//
// NNEDI3 neural-network upscaler applied as post-processing (the game's sprites and
// textures are not modified, only the final image). Original NNEDI3 algorithm by tritical;
// weights from bjin/mpv-prescalers (LGPL-3.0), as shipped in PPSSPP's tex_nnedi3 shaders.

#ifdef GL_ES
#ifdef GL_FRAGMENT_PRECISION_HIGH
precision highp float;
#else
precision mediump float;
#endif
#endif

uniform sampler2D sampler0;
varying vec2 v_texcoord0;

uniform vec2 u_texelDelta;

const vec3 LUMA = vec3(0.299, 0.587, 0.114);
"""

# Pass 1 reads the game image at 1x. PPSSPP renders at exactly 480x272 when the first shader
# is an upscaler; the source buffer can be wider (e.g. 512), so clamp to the game area.
V_PASS = """
const vec2 GAME_SIZE = vec2(480.0, 272.0);

vec3 Src(vec2 pixel) {{
	vec2 c = clamp(pixel, vec2(0.0), GAME_SIZE - 1.0) + 0.5;
	return texture2D(sampler0, c * u_texelDelta).rgb;
}}

{fetch_window}

void main() {{
	vec2 p = v_texcoord0 / u_texelDelta;   // position in source pixels
	vec2 sp = floor(p);                      // source pixel
	vec2 half2 = floor(fract(p) * 2.0);      // which of the 2x2 output pixels this is
	if (half2.x > 0.5) {{
		// Odd columns are never read by the horizontal pass.
		gl_FragColor = vec4(0.0, 0.0, 0.0, 1.0);
		return;
	}}
	vec3 here = Src(sp);
	if (half2.y < 0.5) {{
		gl_FragColor = vec4(here, 1.0);   // Original row.
		return;
	}}
	// New row between source rows sp.y and sp.y + 1.
{predict}
	gl_FragColor = vec4(clamp(color, 0.0, 1.0), 1.0);
}}
"""

# Pass 2 reads pass 1's 960x544 image, where the vertically doubled picture lives in the
# even columns: V(c, r) = P1(2c, r).
H_PASS = """
vec2 Size2x() {{
	return 1.0 / u_texelDelta;   // 960 x 544
}}

vec3 Src(vec2 pixel) {{
	// pixel = (column of the vertically doubled image, row)
	vec2 size = Size2x();
	vec2 c = clamp(pixel, vec2(0.0), vec2(size.x * 0.5 - 1.0, size.y - 1.0));
	return texture2D(sampler0, (vec2(c.x * 2.0, c.y) + 0.5) * u_texelDelta).rgb;
}}

{fetch_window}

void main() {{
	vec2 q = floor(v_texcoord0 / u_texelDelta);   // output pixel in the 960x544 image
	float col = floor(q.x * 0.5);
	vec2 sp = vec2(col, q.y);
	vec3 here = Src(sp);
	if (q.x - col * 2.0 < 0.5) {{
		gl_FragColor = vec4(here, 1.0);   // Original column.
		return;
	}}
	// New column between columns sp.x and sp.x + 1.
{predict}
	gl_FragColor = vec4(clamp(color, 0.0, 1.0), 1.0);
}}
"""

# The two kernels read their 8x4 windows in different orders (see the .csh source).
V_WINDOW = [[(k - 3, m - 1) for m in range(4)] for k in range(8)]
H_WINDOW = []
for dx in (-1, 0, 1, 2):
    H_WINDOW.append([(dx, dy) for dy in (-3, -2, -1, 0)])
    H_WINDOW.append([(dx, dy) for dy in (1, 2, 3, 4)])


def window_fetch(name, window, comp):
    """Function returning the 8 sample vectors for one channel / luma, as out params."""
    lines = ["void %s(vec2 sp, out vec4 s0, out vec4 s1, out vec4 s2, out vec4 s3, out vec4 s4, out vec4 s5, out vec4 s6, out vec4 s7) {" % name]
    # Fetch each distinct pixel once.
    pts = sorted({pt for row in window for pt in row})
    for (dx, dy) in pts:
        var = "t_%s_%s" % (("m%d" % -dx) if dx < 0 else dx, ("m%d" % -dy) if dy < 0 else dy)
        lines.append("\tvec3 %s = Src(sp + vec2(%s, %s));" % (var, lit(dx), lit(dy)))
    for k, row in enumerate(window):
        vals = []
        for (dx, dy) in row:
            var = "t_%s_%s" % (("m%d" % -dx) if dx < 0 else dx, ("m%d" % -dy) if dy < 0 else dy)
            vals.append(comp(var))
        lines.append("\ts%d = vec4(%s);" % (k, ", ".join(vals)))
    lines.append("}")
    return "\n".join(lines)


def window_fetch_rgb(name, window):
    """Fetches the window once and returns 8 vec4 per channel (24 out params)."""
    lines = ["void %s(vec2 sp," % name]
    params = []
    for ch in "rgb":
        params.append(", ".join("out vec4 %s%d" % (ch, k) for k in range(8)))
    lines[0] += " " + ", ".join(params) + ") {"
    pts = sorted({pt for row in window for pt in row})
    for (dx, dy) in pts:
        var = "t_%s_%s" % (("m%d" % -dx) if dx < 0 else dx, ("m%d" % -dy) if dy < 0 else dy)
        lines.append("\tvec3 %s = Src(sp + vec2(%s, %s));" % (var, lit(dx), lit(dy)))
    for ch in "rgb":
        for k, row in enumerate(window):
            vals = []
            for (dx, dy) in row:
                var = "t_%s_%s" % (("m%d" % -dx) if dx < 0 else dx, ("m%d" % -dy) if dy < 0 else dy)
                vals.append("%s.%s" % (var, ch))
            lines.append("\t%s%d = vec4(%s);" % (ch, k, ", ".join(vals)))
    lines.append("}")
    return "\n".join(lines)


def predict_block(direction, rgb):
    """GLSL statements computing `vec3 color` for the new pixel."""
    kern = "Nnedi3V" if direction == "v" else "Nnedi3H"
    step = "vec2(0.0, 1.0)" if direction == "v" else "vec2(1.0, 0.0)"
    if rgb:
        return "\n".join([
            "\tvec4 r0, r1, r2, r3, r4, r5, r6, r7, g0, g1, g2, g3, g4, g5, g6, g7, b0, b1, b2, b3, b4, b5, b6, b7;",
            "\tWindowRGB(sp, r0, r1, r2, r3, r4, r5, r6, r7, g0, g1, g2, g3, g4, g5, g6, g7, b0, b1, b2, b3, b4, b5, b6, b7);",
            "\tvec3 color = vec3(%s(r0, r1, r2, r3, r4, r5, r6, r7)," % kern,
            "\t\t%s(g0, g1, g2, g3, g4, g5, g6, g7)," % kern,
            "\t\t%s(b0, b1, b2, b3, b4, b5, b6, b7));" % kern,
        ])
    return "\n".join([
        "\tvec4 s0, s1, s2, s3, s4, s5, s6, s7;",
        "\tWindowLuma(sp, s0, s1, s2, s3, s4, s5, s6, s7);",
        "\tfloat predicted = %s(s0, s1, s2, s3, s4, s5, s6, s7);" % kern,
        "\t// Color from Catmull-Rom halfway between the two neighbours, matched to the",
        "\t// brightness the network predicted.",
        "\tvec3 a = Src(sp - %s);" % step,
        "\tvec3 b = here;",
        "\tvec3 c = Src(sp + %s);" % step,
        "\tvec3 d = Src(sp + 2.0 * %s);" % step,
        "\tvec3 cubic = (-a + 9.0 * b + 9.0 * c - d) * (1.0 / 16.0);",
        "\t// Keep the cubic estimate inside the neighbours' range to avoid halos.",
        "\tcubic = clamp(cubic, min(b, c), max(b, c));",
        "\tvec3 color = cubic + (predicted - dot(cubic, LUMA));",
    ])


def build(direction, rgb, neurons):
    title = "NNEDI3 %s pass (%s)" % ("vertical" if direction == "v" else "horizontal",
                                      "RGB" if rgb else "luma")
    kern_name = "Nnedi3V" if direction == "v" else "Nnedi3H"
    window = V_WINDOW if direction == "v" else H_WINDOW
    if rgb:
        fetch = window_fetch_rgb("WindowRGB", window)
    else:
        fetch = window_fetch("WindowLuma", window, lambda var: "dot(%s, LUMA)" % var)
    body = (V_PASS if direction == "v" else H_PASS).format(
        fetch_window=kernel_glsl(kern_name, neurons) + "\n\n" + fetch,
        predict=predict_block(direction, rgb))
    return HEADER.format(title=title) + body


def main(ppsspp_dir, out_dir):
    src_path = os.path.join(ppsspp_dir, "assets", "shaders", "tex_nnedi3_2x_single.csh")
    src = open(src_path, encoding="utf-8").read()
    vertical = extract_kernel(src, "nnedi3VerticalKernel")
    horizontal = extract_kernel(src, "nnedi3HorizontalKernel")
    os.makedirs(out_dir, exist_ok=True)
    outputs = {
        "acplus_nnedi3_v.fsh": build("v", False, vertical),
        "acplus_nnedi3_h.fsh": build("h", False, horizontal),
        "acplus_nnedi3_rgb_v.fsh": build("v", True, vertical),
        "acplus_nnedi3_rgb_h.fsh": build("h", True, horizontal),
    }
    for name, text in outputs.items():
        with open(os.path.join(out_dir, name), "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", name, "(%d lines)" % text.count("\n"))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
