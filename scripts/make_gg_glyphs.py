#!/usr/bin/env python3
"""Generates assets/ui_images/gg_buttons.svg: the P, K, S, HS and D labels (Guilty Gear) and
LP, MP, HP, LK, MK, HK (Street Fighter Alpha 3) used by the arcade-style touch buttons, drawn from PPSSPP's own Roboto Condensed Bold font.

Usage: python3 scripts/make_gg_glyphs.py <path/to/Roboto_Condensed-Bold.ttf> <output.svg>

Each label becomes one <path id="I_GG_..."> that PPSSPP's UI atlas rasterizes (UI/UIAtlas.cpp).
Labels are laid out far apart so their bounding boxes never overlap.
"""
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

LABELS = [("I_GG_P", "P"), ("I_GG_K", "K"), ("I_GG_S", "S"), ("I_GG_HS", "HS"), ("I_GG_D", "D"),
          # Street Fighter Alpha 3: light / medium / heavy punch and kick.
          ("I_SF_LP", "LP"), ("I_SF_MP", "MP"), ("I_SF_HP", "HP"), ("I_SF_LK", "LK"), ("I_SF_MK", "MK"), ("I_SF_HK", "HK"),
          # Shortcut buttons of the "Móvil" layout (smaller letters: they go on smaller buttons).
          ("I_AC_RC", "RC", 24), ("I_AC_BURST", "BURST", 16), ("I_AC_ROLL", "ROLL", 19), ("I_AC_CD", "CD", 24),
          ("I_AC_MAX", "MAX", 21), ("I_AC_VISM", "V-ISM", 16)]
CAP_HEIGHT_PX = 30.0  # Same visual size as PPSSPP's I_A..I_F letters (about 31 px).
SLOT_WIDTH = 120.0
MARGIN = 10.0


def main(font_path, out_path):
    font = TTFont(font_path)
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    cap_height = getattr(font["OS/2"], "sCapHeight", 0) or font["head"].unitsPerEm * 0.7
    scale = CAP_HEIGHT_PX / cap_height
    height = CAP_HEIGHT_PX + 2 * MARGIN

    paths = []
    for slot, entry in enumerate(LABELS):
        image_id, text = entry[0], entry[1]
        cap = entry[2] if len(entry) > 2 else CAP_HEIGHT_PX
        scale = cap / cap_height
        # Measure the label width to center it in its slot.
        advance = sum(glyph_set[cmap[ord(ch)]].width for ch in text)
        tracking = 0.04 * font["head"].unitsPerEm
        total = advance + tracking * (len(text) - 1)
        x0 = slot * SLOT_WIDTH + (SLOT_WIDTH - total * scale) / 2
        baseline = MARGIN + (CAP_HEIGHT_PX + cap) / 2

        pen = SVGPathPen(glyph_set, ntos=lambda v: ("%.2f" % v).rstrip("0").rstrip("."))
        cursor = 0.0
        for ch in text:
            name = cmap[ord(ch)]
            # Font units are y-up; SVG is y-down. Bake the transform into the coordinates.
            tpen = TransformPen(pen, (scale, 0, 0, -scale, x0 + cursor * scale, baseline))
            glyph_set[name].draw(tpen)
            cursor += glyph_set[name].width + tracking
        d = pen.getCommands()
        paths.append('  <path id="%s" aria-label="%s" style="fill:#ffffff;fill-rule:nonzero" d="%s" />' % (image_id, text, d))

    width = SLOT_WIDTH * len(LABELS)
    svg = (
        '<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n'
        '<!-- Generated by scripts/make_gg_glyphs.py from Roboto Condensed Bold (Apache License 2.0). -->\n'
        '<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="%d" height="%d" viewBox="0 0 %d %d">\n'
        '%s\n</svg>\n' % (width, height, width, height, "\n".join(paths))
    )
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(svg)
    print("wrote", out_path, "(%dx%d)" % (width, height))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
